function makeBooking({
  id,
  equipmentId,
  customer,
  startDate,
  endDate,
  quantity,
  status,
  paymentStatus,
  createdAt,
  phone = '+8801712345678',
  address = 'House 7, Road 5, Block C, Mirpur, Dhaka',
  notes = '',
  holdExpiresAt = null,
  transactionId = null,
}) {
  const item = bookingEquipment[equipmentId];
  const days = computeDays(startDate, endDate);
  const units = computeUnits(days, item.rentalType);
  const totalAmount = computeTotal(item.price, units, quantity);

  return {
    id,
    equipmentId,
    equipment: {
      name: item.name,
      image: item.image,
      category: item.category,
      rentalType: item.rentalType,
      price: item.price,
    },
    owner: { id: item.owner.id, name: item.owner.name, email: item.owner.email },
    customer,
    startDate,
    endDate,
    quantity,
    days,
    units,
    totalAmount,
    phone,
    address,
    notes,
    status,
    paymentStatus,
    holdExpiresAt,
    checkoutSessionId: null,
    transactionId,
    createdAt,
    updatedAt: createdAt,
  };
}

